#!/usr/bin/env python3
"""Behavior 89: the home's background is a dotted map of Australia drawn from the
engine's own suburbs, not a hand-drawn outline. This reads every suburb's centroid
(GET /api/suburbs?state=ALL on a running stack), snaps them to a 0.8-degree grid and
writes one dot per occupied cell, with a weight 1-3 for how many suburbs fall in it
(the cities glow), filling inland gaps at weight 0, to
shell/web/frontend/src/lib/homeDots.ts.

    python3 scripts/gen_home_dots.py http://127.0.0.1:5173
"""
import json
import sys
import urllib.request
from pathlib import Path

CELL = 0.8
LON0, LAT0 = 112.0, -9.0  # the grid's top-left (west, north)
OUT = Path(__file__).resolve().parent.parent / "shell/web/frontend/src/lib/homeDots.ts"


def main(base: str) -> None:
    with urllib.request.urlopen(f"{base}/api/suburbs?state=ALL") as r:
        suburbs = json.load(r)["suburbs"]
    cells: dict[tuple[int, int], int] = {}
    for s in suburbs:
        c = s.get("centroid")
        if not c:
            continue
        k = (round((c["lon"] - LON0) / CELL), round((LAT0 - c["lat"]) / CELL))
        cells[k] = cells.get(k, 0) + 1
    w = lambda n: 3 if n >= 40 else 2 if n >= 8 else 1
    # The outback holds few suburbs, so the raw cells leave holes in the continent: an
    # empty cell with an occupied cell somewhere on each of its four sides (along its
    # row and its column) is inland and is filled, at weight 0 (the faintest).
    ys = {k[1] for k in cells}
    filled = {}
    for y in range(min(ys), max(ys) + 1):
        row = sorted(x for x, yy in cells if yy == y)
        for x in range(row[0], row[-1] + 1) if row else ():
            if (x, y) in cells:
                continue
            col = [yy for xx, yy in cells if xx == x]
            if col and min(col) < y < max(col):
                filled[(x, y)] = 0
    weights = {k: w(n) for k, n in cells.items()} | filled
    flat = [v for (x, y), wt in sorted(weights.items(), key=lambda kv: (kv[0][1], kv[0][0])) for v in (x, y, wt)]
    cols = max(x for x, _ in cells) + 1
    rows = max(y for _, y in cells) + 1
    OUT.write_text(
        "// Generated by scripts/gen_home_dots.py from the engine's suburbs (behavior 89): one\n"
        f"// dot per {CELL}-degree cell holding a suburb's centroid, as x, y, weight (1-3, how\n"
        "// many suburbs the cell holds; 0 an inland gap filled between them). Regenerate\n"
        "// with that script; do not edit by hand.\n"
        f"export const DOT_COLS = {cols};\nexport const DOT_ROWS = {rows};\n"
        f"export const DOTS: readonly number[] = {json.dumps(flat, separators=(',', ':'))};\n"
    )
    print(f"{len(cells)} dots + {len(filled)} inland, {cols}x{rows} -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:5173")
